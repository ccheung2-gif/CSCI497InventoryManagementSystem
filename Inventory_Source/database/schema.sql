-- Inventory Management System database
-- Running this SQL script will create the database schema for the Inventory Management System. It will drop any existing tables and create new empty tables.
-- 2026-11-14: cut from 11 tables to 7. ROLE became a column in USER, PRODUCT_SUPPLIER became
-- SUPPLIER_ID in PRODUCT, and PURCHASE_ORDER / PURCHASE_ORDER_ITEM were removed.
-- The old version is saved in ../backup-before-table-cut/.


PRAGMA foreign_keys = ON;

-- Remove old tables
-- (The first four are no longer used. They are still dropped so an old database gets cleaned up.)
DROP TABLE IF EXISTS PURCHASE_ORDER_ITEM;
DROP TABLE IF EXISTS PURCHASE_ORDER;
DROP TABLE IF EXISTS PRODUCT_SUPPLIER;
DROP TABLE IF EXISTS INVENTORY_MOVEMENT;
DROP TABLE IF EXISTS STOCK_LEVEL;
DROP TABLE IF EXISTS INVENTORY_LOCATION;
DROP TABLE IF EXISTS PRODUCT;
DROP TABLE IF EXISTS SUPPLIER;
DROP TABLE IF EXISTS CATEGORY;
DROP TABLE IF EXISTS USER;
DROP TABLE IF EXISTS ROLE;


-- ROLE is a plain text column now. The CHECK rule allows only these two values.
CREATE TABLE USER (
    USER_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    USERNAME TEXT NOT NULL UNIQUE,
    FIRST_LAST_NAME TEXT NOT NULL,
    ROLE TEXT NOT NULL CHECK (ROLE IN ('Admin', 'Staff'))
);


CREATE TABLE CATEGORY (
    CATEGORY_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    CATEGORY_NAME TEXT NOT NULL UNIQUE
);


-- SUPPLIER comes before PRODUCT because PRODUCT now points to it.
CREATE TABLE SUPPLIER (
    SUPPLIER_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    SUPPLIER_NAME TEXT NOT NULL,
    PHONE_NUMBER TEXT NOT NULL,
    EMAIL TEXT NOT NULL
);


-- Each product has at most one supplier (SUPPLIER_ID can be empty).
CREATE TABLE PRODUCT (
    PRODUCT_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    SKU TEXT NOT NULL UNIQUE,
    PRODUCT_NAME TEXT NOT NULL,
    PRICE REAL NOT NULL CHECK (PRICE >= 0),
    CATEGORY_ID INTEGER,
    SUPPLIER_ID INTEGER,
    FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY(CATEGORY_ID),
    FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIER(SUPPLIER_ID)
);


CREATE TABLE INVENTORY_LOCATION (
    LOCATION_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    LOCATION_NAME TEXT NOT NULL UNIQUE
);
-- Stock levels of products at each location. Reorder level is the minimum count before we need to order more.
CREATE TABLE STOCK_LEVEL (
    STOCK_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    PRODUCT_ID INTEGER NOT NULL,
    LOCATION_ID INTEGER NOT NULL,
    REORDER_LEVEL INTEGER NOT NULL CHECK (REORDER_LEVEL >= 0),
    QUANTITY INTEGER NOT NULL CHECK (QUANTITY >= 0),
    UNIQUE (PRODUCT_ID, LOCATION_ID),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID),
    FOREIGN KEY (LOCATION_ID) REFERENCES INVENTORY_LOCATION(LOCATION_ID)
);


CREATE TABLE INVENTORY_MOVEMENT (
    MOVEMENT_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    PRODUCT_ID INTEGER NOT NULL,
    LOCATION_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    MOVEMENT_TYPE TEXT NOT NULL CHECK (MOVEMENT_TYPE IN ('Receipt', 'Issue', 'Transfer', 'Adjustment')),
    QUANTITY INTEGER NOT NULL CHECK (QUANTITY <> 0),
    MOVEMENT_DATE TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID),
    FOREIGN KEY (LOCATION_ID) REFERENCES INVENTORY_LOCATION(LOCATION_ID),
    FOREIGN KEY (USER_ID) REFERENCES USER(USER_ID)
);


-- Indexes
CREATE INDEX INDEX_PRODUCT_NAME ON PRODUCT(PRODUCT_NAME);
CREATE INDEX INDEX_STOCK_LOW ON STOCK_LEVEL(PRODUCT_ID, LOCATION_ID) WHERE QUANTITY <= REORDER_LEVEL;
