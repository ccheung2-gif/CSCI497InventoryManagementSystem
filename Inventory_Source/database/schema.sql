-- Inventory Management System database
-- Running this script drops the old tables and creates new empty ones.
-- Only what the screens use: products, categories, suppliers, locations.

PRAGMA foreign_keys = ON;

-- old tables (dropped so an old database gets cleaned up)
DROP TABLE IF EXISTS PURCHASE_ORDER_ITEM;
DROP TABLE IF EXISTS PURCHASE_ORDER;
DROP TABLE IF EXISTS PRODUCT_SUPPLIER;
DROP TABLE IF EXISTS INVENTORY_MOVEMENT;
DROP TABLE IF EXISTS STOCK_LEVEL;
DROP TABLE IF EXISTS USER;
DROP TABLE IF EXISTS ROLE;

-- current tables, PRODUCT first since it points at the others
DROP TABLE IF EXISTS PRODUCT;
DROP TABLE IF EXISTS INVENTORY_LOCATION;
DROP TABLE IF EXISTS SUPPLIER;
DROP TABLE IF EXISTS CATEGORY;


CREATE TABLE CATEGORY (
    CATEGORY_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    CATEGORY_NAME TEXT NOT NULL UNIQUE
);


CREATE TABLE SUPPLIER (
    SUPPLIER_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    SUPPLIER_NAME TEXT NOT NULL UNIQUE
);


CREATE TABLE INVENTORY_LOCATION (
    LOCATION_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    LOCATION_NAME TEXT NOT NULL UNIQUE
);


-- one row per item. category, supplier, and location can be empty
-- reorder level is the count where the item shows as low stock
CREATE TABLE PRODUCT (
    PRODUCT_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    PRODUCT_NAME TEXT NOT NULL,
    DESCRIPTION TEXT,
    CATEGORY_ID INTEGER,
    SUPPLIER_ID INTEGER,
    LOCATION_ID INTEGER,
    QUANTITY INTEGER NOT NULL DEFAULT 0 CHECK (QUANTITY >= 0),
    REORDER_LEVEL INTEGER NOT NULL DEFAULT 0 CHECK (REORDER_LEVEL >= 0),
    PRICE REAL NOT NULL DEFAULT 0 CHECK (PRICE >= 0),
    FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY(CATEGORY_ID),
    FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIER(SUPPLIER_ID),
    FOREIGN KEY (LOCATION_ID) REFERENCES INVENTORY_LOCATION(LOCATION_ID)
);
